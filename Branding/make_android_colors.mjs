// Generates the Android app's brand colour schemes (android/app/.../ui/BrandColors.kt) with Google's
// material-color-utilities, so the palette follows Material 3's tonal system rather than hand-picked tones.
//
//   Primary and secondary: SchemeFidelity from Signal Blue #1B4F9E (primaryContainer is exactly the brand blue).
//   Tertiary: Beam Cyan #46C8FF (Fidelity's own tertiary is a complementary brown).
//   Neutrals: hue of the brand's light neutral #F5F5F7; backgrounds are exactly #F5F5F7 / Graphite #1C1C1E,
//   with the surface-container ladder spaced around them so cards still stand off the background.
//
// Usage (the 0.4.0 package has a broken ESM import; 0.3.0 works):
//   npm install --prefix <tmp> @material/material-color-utilities@0.3.0
//   node Branding/make_android_colors.mjs <tmp>/node_modules/@material/material-color-utilities/index.js \
//     > android/app/src/main/kotlin/com/charan/wifibar/ui/BrandColors.kt
const lib = await import(process.argv[2]);
const { argbFromHex, hexFromArgb, Hct, SchemeFidelity, DynamicScheme, TonalPalette, MaterialDynamicColors } = lib;

const SIGNAL_BLUE = "#1B4F9E", BEAM_CYAN = "#46C8FF", LIGHT_NEUTRAL = "#F5F5F7", GRAPHITE = "#1C1C1E";
const seed = Hct.fromInt(argbFromHex(SIGNAL_BLUE));
const cyan = Hct.fromInt(argbFromHex(BEAM_CYAN));
const neutral = Hct.fromInt(argbFromHex(LIGHT_NEUTRAL));
const roles = ["primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary", "secondary", "onSecondary",
  "secondaryContainer", "onSecondaryContainer", "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer", "background",
  "onBackground", "surface", "onSurface", "surfaceVariant", "onSurfaceVariant", "surfaceTint", "inverseSurface", "inverseOnSurface",
  "error", "onError", "errorContainer", "onErrorContainer", "outline", "outlineVariant", "scrim", "surfaceBright", "surfaceDim",
  "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest", "surfaceContainerLow", "surfaceContainerLowest"];

function scheme(dark) {
  const fidelity = new SchemeFidelity(seed, dark, 0.0);
  const s = new DynamicScheme({
    sourceColorArgb: seed.toInt(), variant: fidelity.variant, contrastLevel: 0.0, isDark: dark,
    primaryPalette: fidelity.primaryPalette, secondaryPalette: fidelity.secondaryPalette,
    tertiaryPalette: TonalPalette.fromHueAndChroma(cyan.hue, cyan.chroma),
    neutralPalette: TonalPalette.fromHueAndChroma(neutral.hue, 2.0),
    neutralVariantPalette: TonalPalette.fromHueAndChroma(seed.hue, 6.0),
  });
  const o = {};
  for (const r of roles) o[r] = hexFromArgb(MaterialDynamicColors[r].getArgb(s)).toUpperCase();
  const t = (tone) => hexFromArgb(s.neutralPalette.tone(tone)).toUpperCase();
  if (dark) {
    Object.assign(o, { background: GRAPHITE, surface: GRAPHITE, surfaceDim: GRAPHITE, surfaceContainerLowest: t(6),
      surfaceContainerLow: t(14), surfaceContainer: t(17), surfaceContainerHigh: t(22), surfaceContainerHighest: t(27), surfaceBright: t(30) });
  } else {
    Object.assign(o, { background: LIGHT_NEUTRAL, surface: LIGHT_NEUTRAL, surfaceBright: LIGHT_NEUTRAL, surfaceContainerLowest: "#FFFFFF",
      surfaceContainerLow: "#FFFFFF", surfaceContainer: t(94), surfaceContainerHigh: t(92), surfaceContainerHighest: t(90), surfaceDim: t(87) });
  }
  return o;
}

const kotlin = (name, fn, o) => `val ${name} = ${fn}(\n` + roles.map((r) => `    ${r} = Color(0xFF${o[r].slice(1)}),`).join("\n") + "\n)\n";
console.log(`package com.charan.wifibar.ui

import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

// Generated by Branding/make_android_colors.mjs from the brand palette (Branding/BRAND.md). Don't edit by hand.

${kotlin("BrandLightColors", "lightColorScheme", scheme(false))}
${kotlin("BrandDarkColors", "darkColorScheme", scheme(true))}
/** Brand accents used directly (sparingly): the router dot and its glow. */
object Brand {
    val InkNavy = Color(0xFF0A1A3A)
    val SignalBlue = Color(0xFF1B4F9E)
    val BeamCyan = Color(0xFF46C8FF)
    val BeamPale = Color(0xFFA6DCFF)
}`);
