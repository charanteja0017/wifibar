#!/bin/zsh
# Builds WiFiBar.app, with its desktop widget, using the Command Line Tools (no Xcode needed).
#   scripts/bundle.sh            release build into build/WiFiBar.app
#   scripts/bundle.sh debug      debug build
#
# Signing: uses a "WiFiBar Local" code-signing certificate from your keychain when present,
# so macOS keeps the Location permission across rebuilds. Otherwise signs ad hoc.
set -euo pipefail

cd "${0:A:h}/.."
config="${1:-release}"
app="build/WiFiBar.app"
appex="$app/Contents/PlugIns/WiFiBarWidget.appex"
identity="WiFiBar Local"

swift build -c "$config" --product WiFiBar
swift build -c "$config" --product WiFiBarWidget
bin="$(swift build -c "$config" --show-bin-path)"

rm -rf "$app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources" "$appex/Contents/MacOS"
cp "$bin/WiFiBar" "$app/Contents/MacOS/WiFiBar"
cp Resources/Info.plist "$app/Contents/Info.plist"
# The brand icon (generated by Branding/make_brand.py) and the About window's credits.
cp Branding/out/AppIcon.icns "$app/Contents/Resources/AppIcon.icns"
cp Resources/Credits.rtf "$app/Contents/Resources/Credits.rtf"
cp "$bin/WiFiBarWidget" "$appex/Contents/MacOS/WiFiBarWidget"
cp Resources/Widget-Info.plist "$appex/Contents/Info.plist"
plutil -lint "$app/Contents/Info.plist" "$appex/Contents/Info.plist" >/dev/null

# A self-signed certificate is "not trusted", so `find-identity -v` would hide it; codesign still uses it.
if security find-identity -p codesigning | grep -q "\"$identity\""; then
  sign="$identity"
else
  sign="-"
fi
# Inside out: the widget (sandboxed, with its entitlements), then the app around it.
codesign --force --sign "$sign" --entitlements Resources/WiFiBarWidget.entitlements "$appex"
codesign --force --sign "$sign" "$app"
codesign --verify --strict --deep "$app"

echo "Built $app"
